def material(mt):
    return {"what": mt[0], "why": mt[1], "steps": mt[2], "example": mt[3]}


def question(q):
    return {"type": q["k"], "q": q["q"], "options": q["o"], "answer": q["a"],
            "ok": q["ok"], "no": q["no"]}


def chapter(c):
    out = {"title": c["t"], "mascot": c["m"], "intro": c["intro"]}
    if c.get("mail"):
        out["mail"] = c["mail"]
    if c.get("mat"):
        out["cards"] = c["mat"]
    if c.get("sty"):
        s = c["sty"]
        out["story"] = {"text": s[0], "best": s[1],
                        "options": [{"t": o[0], "r": o[1]} for o in s[2:]]}
    out["questions"] = [question(q) for q in c["qs"]]
    return out


